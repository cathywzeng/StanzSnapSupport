function applyLang(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[lang] && i18n[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = i18n[lang][key];
      } else {
        el.innerHTML = i18n[lang][key];
      }
    }
  });
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  localStorage.setItem('stanzsnap-lang', lang);
  updateGuideImages(lang);
}

function updateGuideImages(lang) {
  var folder = lang === 'zh' ? 'chinese' : 'english';
  document.querySelectorAll('.guide-screenshot').forEach(img => {
    img.src = img.getAttribute('src').replace(/assets\/(chinese|english)\//, 'assets/' + folder + '/');
  });
}

function toggleLang() {
  const current = localStorage.getItem('stanzsnap-lang') || 'zh';
  const next = current === 'zh' ? 'en' : 'zh';
  applyLang(next);
}

// On load, apply saved language
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('stanzsnap-lang');
  if (saved && saved !== 'zh') {
    applyLang(saved);
  }
});
